/**
 * 将繁体中文转换为简体中文
 */
export function t2s(text: string): string {
  if (!text) return text
  let result = ''
  for (const char of text) {
    result += T2S_MAP[char] || char
  }
  return result
}

/**
 * 根据 locale 决定是否转换
 * - zh-CN: 转换为简体
 * - zh-HK/en/其他: 保持原样（繁体）
 */
export function localizeText(text: string, locale: string): string {
  if (locale === 'zh-CN') {
    return t2s(text)
  }
  return text
}
